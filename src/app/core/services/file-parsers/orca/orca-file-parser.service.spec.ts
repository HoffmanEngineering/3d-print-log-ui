import { TestBed } from '@angular/core/testing';

import { OrcaFileParserService } from './orca-file-parser.service';
import { ORCA_TWO_FILAMENT_GCODE } from '../fixtures/orca-two-filament.fixture';

describe('OrcaFileParserService', () => {
  let service: OrcaFileParserService;

  beforeEach(() => {
    TestBed.configureTestingModule({});
    service = TestBed.inject(OrcaFileParserService);
  });

  it('should be created', () => {
    expect(service).toBeTruthy();
  });

  it('should parse the estimated print time using the normal mode when estimation exist in the gcode', async () => {
    const testGcode = `; HEADER_BLOCK_START
    ; generated by OrcaSlicer 1.7.0 on 2023-09-23 at 14:31:55
    ; model printing time: 1h 25m 2s; total estimated time: 1h 30m 53s
    ; total layer number: 22
    ; model label id: 89,109,129
    ; HEADER_BLOCK_END`;
    const expectedEstPrintTime = 5453;

    const actual = await service.parse(testGcode);

    expect(actual.estimatedPrintTimeInSeconds).toBe(expectedEstPrintTime);
  });

  it('should set the estimated print time to undefined when no estimations exist in the gcode', async () => {
    const testGcodeWithoutEstimations = `; total filament used [g] = 0.0
    ; total filament cost = 0.0`;

    const actual = await service.parse(testGcodeWithoutEstimations);

    expect(actual.estimatedPrintTimeInSeconds).toBeUndefined();
  });

  describe('estimateFilamentUsageInMg', () => {
    it('should return undefined when diameter or length is missing or zero', () => {
      const invalidInputs = [
        `; filament_type = PLA
; filament used [mm] = 1000`,
        `; filament_type = PLA
; filament_diameter = 1.75`,
        `; filament_type = PLA
; filament_diameter = 0
; filament used [mm] = 1000`,
        `; filament_type = PLA
; filament_diameter = 1.75
; filament used [mm] = 0`,
      ];

      invalidInputs.forEach((gcode) => {
        expect(service.estimateFilamentUsageInMg(gcode)).toBeUndefined();
      });
    });
  });
});

describe('OrcaFileParserService multi-filament', () => {
  let service: OrcaFileParserService;

  beforeEach(() => {
    TestBed.configureTestingModule({});
    service = TestBed.inject(OrcaFileParserService);
  });

  it('emits one usage row per used slot', async () => {
    const print = await service.parse(ORCA_TWO_FILAMENT_GCODE, 'cube.gcode');
    expect(print.filamentUsage.length).toBe(2);
    expect(print.filamentUsage[0].estimatedLengthInM).toBe(1.235);
    expect(print.filamentUsage[0].notes).toBe('Slot 1 · #FF0000 · PLA');
    expect(print.filamentUsage[1].estimatedLengthInM).toBe(0.568);
    expect(print.filamentUsage[1].notes).toBe('Slot 3 · #0000FF · PETG');
    expect(print.estimatedPrintTimeInSeconds).toBe(3723);
    expect(print.title).toBe('Cube');
  });

  it('keeps the notes text unchanged', async () => {
    const print = await service.parse(ORCA_TWO_FILAMENT_GCODE);
    expect(print.notes).toBe(`Print Settings:
Print Setting Config: 0.20mm Standard @BBL X1C
Printer Config: Bambu Lab X1 Carbon 0.4 nozzle
Layer Count: 50
Layer Height: 0.2mm
Top Layer Count: 4
Bottom Layer Count: 3
Walls: 2
Infill: 15%
Infill Pattern: grid
Support: No Supports`);
  });

  describe('support notes', () => {
    // Real OrcaSlicer 2.2.0 output writes both keys: enable_support is the
    // switch, support_filament is the filament index for supports (0 = default).
    const withSupport = (lines: string) =>
      ORCA_TWO_FILAMENT_GCODE.replace('; support_filament = 0', lines);

    it('reports supports from enable_support even when support_filament is the default', async () => {
      const print = await service.parse(
        withSupport('; enable_support = 1\n; support_filament = 0')
      );
      expect(print.notes).toContain('Support: Enabled Everywhere');
    });

    it('reports build-plate-only supports', async () => {
      const print = await service.parse(
        withSupport(
          '; enable_support = 1\n; support_filament = 0\n; support_on_build_plate_only = 1'
        )
      );
      expect(print.notes).toContain('Support: Enabled Touching Buildplate');
    });

    it('reports no supports when enable_support is off, whatever filament is picked for them', async () => {
      const print = await service.parse(
        withSupport('; enable_support = 0\n; support_filament = 1')
      );
      expect(print.notes).toContain('Support: No Supports');
    });
  });

  it('detects the OrcaSlicer marker', () => {
    expect(service.detect('; generated by OrcaSlicer 2.2.0 on')).toBe(true);
    expect(service.detect('; generated by PrusaSlicer 2.9')).toBe(false);
  });

  it('reports the printer the file was sliced for beside the print', async () => {
    const { print, detectedPrinterNames } = await service.parseWithMeta(
      ORCA_TWO_FILAMENT_GCODE,
      'cube.gcode'
    );
    expect(detectedPrinterNames).toEqual(['Bambu Lab X1 Carbon 0.4 nozzle']);
    // The print is the one parse() returns; startDate is "now", so compare without it.
    const plain = await service.parse(ORCA_TWO_FILAMENT_GCODE, 'cube.gcode');
    expect({ ...print, startDate: null }).toEqual({
      ...plain,
      startDate: null,
    });
  });
});
